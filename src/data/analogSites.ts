// Generates a deterministic, physically shaped DEM grid for each site using its seed & terrain metrics
function generateSiteTopography(
  seed: number,
  slope: number,
  relief: number,
  size = 24
): number[][] {
  const grid: number[][] = [];
  let s = seed;
  const rand = () => {
    s = (s * 1664525 + 1013904223) >>> 0;
    return (s & 0xffff) / 0xffff;
  };

  const raw: number[][] = [];
  for (let i = 0; i < size; i++) {
    raw.push([]);
    for (let j = 0; j < size; j++) {
      raw[i].push(rand());
    }
  }

  // Multi-octave Perlin-like fractal interpolation
  const slopeFactor = Math.min(1.0, slope / 15.0);
  const roughness = 0.35 + 0.65 * slopeFactor;

  for (let i = 0; i < size; i++) {
    const row: number[] = [];
    for (let j = 0; j < size; j++) {
      let h = 0;
      let amp = 1.0;
      let freq = 1;
      let norm = 0;
      for (let oct = 0; oct < 4; oct++) {
        const si = Math.min(size - 1, Math.floor((i / size) * freq * size));
        const sj = Math.min(size - 1, Math.floor((j / size) * freq * size));
        h += raw[si][sj] * amp;
        norm += amp;
        amp *= 0.5 * roughness;
        freq *= 2;
      }
      // center elevation bump with directional slope tilt
      const cx = (j - size / 2) / (size / 2);
      const cy = (i - size / 2) / (size / 2);
      const dist = Math.sqrt(cx * cx + cy * cy);
      const centerDome = Math.exp(-dist * 1.5) * 0.4;
      const slopeTilt = (cy * slopeFactor + cx * 0.2) * 0.3;

      const finalH = Math.max(0.02, Math.min(0.98, (h / norm) * 0.6 + centerDome + slopeTilt));
      row.push(finalH);
    }
    grid.push(row);
  }
  return grid;
}

